// Builds the university list from the US Department of Education's IPEDS
// institution directory (public domain):
//   https://nces.ed.gov/ipeds/datacenter/data/HD2024.zip
// Usage: node scripts/universities.mjs path/to/HD2024.csv
// Writes public/universities.json (the picker's list) and the SQL migration
// that seeds the same rows into public.universities.
import { readFileSync, writeFileSync } from 'node:fs';

const MIGRATION = 'supabase/migrations/20261015010100_seed_universities.sql';

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') (cell += '"'), i++;
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') row.push(cell), (cell = '');
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cell);
      rows.push(row);
      row = [];
      cell = '';
    } else cell += c;
  }
  if (cell || row.length) row.push(cell), rows.push(row);
  return rows;
}

const file = process.argv[2];
if (!file) throw new Error('Pass the path to the IPEDS HD csv.');
const [head, ...body] = parseCsv(readFileSync(file, 'utf8').replace(/^﻿/, ''));
const col = Object.fromEntries(head.map((h, i) => [h.trim(), i]));
const get = (r, k) => (r[col[k]] || '').trim();

// active, degree-granting institutions that haven't closed
const list = body
  .filter(r => r.length === head.length && get(r, 'DEGGRANT') === '1' && get(r, 'CYACTIVE') === '1' && get(r, 'CLOSEDAT') === '-2')
  .map(r => {
    const alias = get(r, 'IALIAS').replace(/\s+/g, ' ');
    return [Number(get(r, 'UNITID')), get(r, 'INSTNM'), get(r, 'CITY'), get(r, 'STABBR'), alias.length > 120 ? alias.slice(0, 120) : alias];
  })
  .sort((a, b) => a[1].localeCompare(b[1]));

writeFileSync('public/universities.json', JSON.stringify(list));

const q = s => `'${s.replace(/'/g, "''")}'`;
const values = list.map(([id, name, city, state]) => `  (${id}, ${q(name)}, ${q(city)}, ${q(state)})`);
writeFileSync(
  MIGRATION,
  `-- Generated by scripts/universities.mjs from the IPEDS ${file.match(/HD\d{4}/i)?.[0] || ''} directory.\n` +
    `insert into public.universities (id, name, city, state) values\n${values.join(',\n')}\n` +
    `on conflict (id) do update set name = excluded.name, city = excluded.city, state = excluded.state;\n`
);
console.log(`${list.length} universities`);
