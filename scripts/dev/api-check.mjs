// node --env-file=.env.local scripts/dev/api-check.mjs: exercise the RPCs as demo users
import { createClient } from '@supabase/supabase-js';
const mk = () => createClient(process.env.VITE_SUPABASE_URL, process.env.VITE_SUPABASE_PUBLISHABLE_KEY, { auth: { persistSession: false } });
const ok = (label, cond, extra = '') => console.log(`${cond ? 'PASS' : 'FAIL'} ${label} ${extra}`);
const a = mk();
let r = await a.auth.signInWithPassword({ email: process.env.DEMO1_EMAIL, password: process.env.DEMO1_PASSWORD });
ok('sign in demo1', !r.error, r.error?.message);
let lb = await a.rpc('get_leaderboard', { p_period: 'all', p_limit: 10 });
ok('leaderboard', !lb.error && lb.data.length >= 3, lb.error?.message || lb.data.map(x => `${x.rank}.${x.username}=${x.best}${x.is_me ? '*' : ''}`).join(' '));
let me = await a.rpc('get_my_stats');
ok('my stats', !me.error && me.data[0].username === 'pizza_goblin', JSON.stringify(me.data?.[0]));
let ins = await a.from('runs').insert({ user_id: me.data[0] && (await a.auth.getUser()).data.user.id, seed: 1, status: 'done', score: 99999 });
ok('direct insert blocked', !!ins.error, ins.error?.message);
let up = await a.from('profiles').update({ username: 'hacker' }).eq('username', 'pizza_goblin').select();
ok('direct profile update blocked', !up.error && up.data.length === 0);
let run = await a.rpc('start_run', { p_seed: 42 });
ok('start run', !run.error, run.error?.message);
let fin = await a.rpc('finish_run', { p_run: run.data, p_score: 99999, p_distance: 100, p_takedowns: 0, p_close_calls: 0, p_duration_ms: 500, p_cause: 'scooter' });
ok('cheat rejected', !fin.error && fin.data[0].result_status === 'rejected', JSON.stringify(fin.data || fin.error));
await new Promise(res => setTimeout(res, 2100));
run = await a.rpc('start_run', { p_seed: 43 });
await new Promise(res => setTimeout(res, 1500));
fin = await a.rpc('finish_run', { p_run: run.data, p_score: 3, p_distance: 20, p_takedowns: 0, p_close_calls: 0, p_duration_ms: 1400, p_cause: 'faceplant' });
ok('legit run accepted', !fin.error && fin.data[0].result_status === 'done', JSON.stringify(fin.data || fin.error));
const b = mk();
r = await b.auth.signInWithPassword({ email: process.env.DEMO4_EMAIL, password: process.env.DEMO4_PASSWORD });
let av = await b.rpc('username_available', { p_username: 'pizza_goblin' });
ok('taken name unavailable', av.data === false);
let bad = await b.rpc('claim_username', { p_username: 'Admin' });
ok('reserved name refused', !!bad.error, bad.error?.message);
let st = await b.rpc('start_run', { p_seed: 1 });
ok('no run without username', !!st.error, st.error?.message);
const anon = mk();
let al = await anon.rpc('get_leaderboard', { p_period: 'all' });
ok('anon cannot read leaderboard', !!al.error, al.error?.message);
